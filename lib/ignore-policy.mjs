// ignore-policy.mjs — the single source of "these paths never reach git".
//
// Why this module exists: the statement was stored TWICE — in the repository's own .gitignore and
// in templates/gitignore.public, from which the published tree's .gitignore is generated. Two
// copies of one statement, with no shared source and nothing comparing them, drift by construction
// rather than by accident. They did: the entries guarding live secrets (opencode.json and friends)
// existed ONLY in the copy that protects other people's machines, and were missing from the copy
// protecting the machine where config/.env actually lives.
//
// This is the fourth instance of that class in this project. v1.7.0 closed three: the
// next_step_prompt cache, framework_version, and two copies of SKILL.md. The first three corrupted
// an instruction; this one publishes keys.
//
// Who uses this module:
//   - the writer — tools/gen-ignore.mjs renders both files from SECTIONS;
//   - the reader — the smoke guard compares what is on disk against diffEntries().
// Dependency direction in this project is core -> lib, so the shared concept lives here.
//
// One list, both trees. That is a measured claim, not a convenience: every difference found
// between the two copies turned out to be drift or a stale entry, never design. See TREE_PARITY.

// The entries whose absence leaks credentials rather than merely adding noise. The guard names
// these separately because "the ignore file changed" and "the ignore file stopped protecting
// secrets" deserve different levels of alarm.
