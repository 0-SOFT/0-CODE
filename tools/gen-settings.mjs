#!/usr/bin/env node
// tools/gen-settings.mjs — builds the settings files from a SINGLE policy source.
//
// WHY (v1.2.0): the settings used to live in two places and drifted apart — the template for
// projects registered the safety-guard hook while the framework's own settings did not have it at
// all. The framework was treating other projects and not itself. Now both files are generated from
// core/permissions-policy.mjs and a test compares them against the source — drift becomes
// technically impossible rather than "fixed once".
//
// Usage:
//   node tools/gen-settings.mjs                      — write the template and this framework's settings
//   node tools/gen-settings.mjs --check              — verify only (exit code 1 on any drift)
//   node tools/gen-settings.mjs --project <dir>      — cure another project's settings (with a backup)
//   node tools/gen-settings.mjs --project <dir> --user — also cure the user-level settings
//   node tools/gen-settings.mjs --project <dir> --dry-run — show what would change, write nothing

import { readFileSync, writeFileSync, existsSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildPermissionsBlock, buildPreToolUseHook, findAskRules } from '../core/permissions-policy.mjs';
import { STOP_HOOK_BLOCK_CAP } from '../core/loop-limits.mjs';
// The cure has to agree with the diagnosis about what counts as a problem, so it takes the
// definition from the doctor rather than keeping a second copy that could drift.
import { isJunkAllowRule, settingsLevels, loadLevel } from './doctor-permissions.mjs';

export const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const TEMPLATE_PATH = join(ROOT, 'templates', 'project-settings.json');
export const SELF_PATH = join(ROOT, '.claude', 'settings.json');

const HOOK_CMD = '${CLAUDE_PROJECT_DIR}/hooks/run-hook.cmd';
const SAFETY_GUARD_CMD = `${HOOK_CMD} safety-guard`;

// The template bootstrap hands out to target projects.
export function buildTemplateSettings() {
  return {
    $schema_comment: 'Generated by node tools/gen-settings.mjs from core/permissions-policy.mjs. Do not edit by hand.',
    env: { CLAUDE_CODE_STOP_HOOK_BLOCK_CAP: String(STOP_HOOK_BLOCK_CAP) },
    hooks: {
      ...buildPreToolUseHook(SAFETY_GUARD_CMD),
      Stop: [{ matcher: '', hooks: [
        { type: 'command', command: `${HOOK_CMD} save-session-log` },
        { type: 'command', command: `${HOOK_CMD} ralph-loop-stop` },
      ] }],
      SessionEnd: [{ matcher: '', hooks: [
        { type: 'command', command: `${HOOK_CMD} save-session-log` },
      ] }],
    },
    // v1.22.0: the status line is the only place Claude Code reveals the plan share, so it is
    // where the share gets recorded (hooks/usage-statusline.mjs). A person's own status line keeps
    // working through USAGE_STATUSLINE_NEXT.
    statusLine: { type: 'command', command: `${HOOK_CMD} usage-statusline` },
    permissions: buildPermissionsBlock(),
  };
}

// Bringing ARBITRARY settings in line with the policy: permissions are replaced wholesale (so the
// forbidden `ask` category disappears), the arbiter hook is added, and the project's other hooks
// are preserved.
export function applyPolicyToSettings(existing = {}) {
  const out = JSON.parse(JSON.stringify(existing || {}));
  out.permissions = buildPermissionsBlock();
  // v1.9.0: the backstop is part of the policy too, so it is brought in line rather than left at
  // whatever an older generation wrote. Everything else in env belongs to the project and stays.
  out.env = { ...(out.env || {}), CLAUDE_CODE_STOP_HOOK_BLOCK_CAP: String(STOP_HOOK_BLOCK_CAP) };
  out.hooks = out.hooks || {};
  const already = (out.hooks.PreToolUse || []).some(entry =>
    (entry.hooks || []).some(h => String(h.command || '').includes('safety-guard')));
  if (!already) {
    out.hooks = { ...buildPreToolUseHook(SAFETY_GUARD_CMD), ...out.hooks };
    if (existing?.hooks?.PreToolUse) {
      out.hooks.PreToolUse = [...buildPreToolUseHook(SAFETY_GUARD_CMD).PreToolUse, ...existing.hooks.PreToolUse];
    }
  }
  return out;
}

// --- Curing an existing settings file (v1.10.0) -----------------------------------------------
//
// WHY THIS EXISTS. The doctor could name the disease and could not treat it: its cure line said
// "run node tools/gen-settings.mjs", and that command only ever knew its own two files. On a real
// project it did nothing at all. Re-running bootstrap does not help either — it deep-merges, and a
// merge unions arrays, so `ask` rules survive because the template has no `ask` key to displace
// them with. The framework could diagnose a project it could not fix.
//
// WHAT THE CURE DOES, AND WHY NOT MORE. The `ask` category is removed outright rather than sorted
// into deny and allow, whatever the doctor's advice used to say. Sorting would mean growing the
// deny list, and the deny list is deliberately tiny: a v1.2.0 measurement showed a broad rule set
// blocking 7 of 11 everyday commands. What decides on a command like `rm -rf build/` is the guard
// hook, not a settings rule.
//
// The framework OWNS a project's .claude/settings.json, so there the whole policy is applied. It
// does NOT own settings.local.json or the user-level file — those are personal — so there the cure
// is surgical: remove what actively breaks autonomy, leave everything else alone.

export function cureSettings(existing = {}, { owned = false } = {}) {
  const before = JSON.parse(JSON.stringify(existing || {}));
  const changes = [];
  const askRules = ((before.permissions || {}).ask) || [];
  const junk = (((before.permissions || {}).allow) || []).filter(isJunkAllowRule);

  let out;
  if (owned) {
    out = applyPolicyToSettings(before);
    if (askRules.length) changes.push(`removed the ask category (${askRules.length} rules): the guard hook decides instead`);
    if (junk.length) changes.push(`removed ${junk.length} hyper-specific allow entries`);
    changes.push('permissions rebuilt from core/permissions-policy.mjs');
  } else {
    out = before;
    if (out.permissions) {
      if (askRules.length) {
        delete out.permissions.ask;
        changes.push(`removed the ask category (${askRules.length} rules): an ask rule outranks every mode and the hook`);
      }
      if (junk.length) {
        out.permissions.allow = out.permissions.allow.filter(r => !isJunkAllowRule(r));
        changes.push(`removed ${junk.length} hyper-specific allow entries left by the "always allow" button`);
      }
    }
  }
  return { settings: out, changes, needsHuman: phantomHooks(before) };
}

// Hooks reading variables that do not exist in the hook contract. These are NOT rewritten
// automatically: what the hook meant to check is a human judgement, and silently deleting somebody
// else's protection would repeat the very mistake of pretending something is guarded when it is not.
export function phantomHooks(settings) {
  const found = [];
  const text = JSON.stringify((settings && settings.hooks) || {});
  for (const v of ['CLAUDE_TOOL_INPUT', 'CLAUDE_TOOL_NAME', 'CLAUDE_COMMAND']) {
    if (text.includes(v)) found.push(v);
  }
  return found;
}

// Differences between a settings file and the policy. An empty array means everything is fine.
export function diffAgainstPolicy(settings) {
  const problems = [];
  const ask = findAskRules(settings);
  if (ask.length) problems.push(`the forbidden ask category is present (${ask.length} rules): ${ask.join(', ')}`);
  const perms = (settings && settings.permissions) || {};
  const expected = buildPermissionsBlock();
  if (perms.defaultMode !== expected.defaultMode)
    problems.push(`defaultMode = ${JSON.stringify(perms.defaultMode)}, expected ${JSON.stringify(expected.defaultMode)}`);
  for (const rule of expected.deny)
    if (!(perms.deny || []).includes(rule)) problems.push(`deny is missing the rule: ${rule}`);
  for (const rule of expected.allow)
    if (!(perms.allow || []).includes(rule)) problems.push(`allow is missing the rule: ${rule}`);
  const hasGuard = Object.values((settings && settings.hooks && settings.hooks.PreToolUse) || [])
    .some(entry => (entry.hooks || []).some(h => String(h.command || '').includes('safety-guard')));
  if (!hasGuard) problems.push('the safety-guard arbiter hook (PreToolUse) is not registered');
  const cap = ((settings && settings.env) || {}).CLAUDE_CODE_STOP_HOOK_BLOCK_CAP;
  if (String(cap) !== String(STOP_HOOK_BLOCK_CAP))
    problems.push(`CLAUDE_CODE_STOP_HOOK_BLOCK_CAP = ${JSON.stringify(cap)}, expected ${JSON.stringify(String(STOP_HOOK_BLOCK_CAP))}`);
  return problems;
}

export function readJson(path) {
  if (!existsSync(path)) return null;
  try { return JSON.parse(readFileSync(path, 'utf8')); }
  catch (e) { return { __parseError: e.message }; }
}

// --- Command-line entry point ---
// Curing the settings of ANOTHER project (or the user-level file). Writes a timestamped backup
// first, the way bootstrap.sh does: this touches files the framework did not write.
function cureFile(path, { owned, dryRun }) {
  const current = readJson(path);
  if (!current) { console.log(`   skip (no file):      ${path}`); return { changed: false }; }
  if (current.__parseError) {
    console.error(`   BROKEN (not JSON):   ${path} — ${current.__parseError}`);
    console.error('   Claude Code ignores a broken settings file SILENTLY, together with every rule in it.');
    return { changed: false, broken: true };
  }
  const { settings, changes, needsHuman } = cureSettings(current, { owned });
  if (!changes.length && !needsHuman.length) { console.log(`   already healthy:     ${path}`); return { changed: false }; }

  for (const c of changes) console.log(`   fix:                 ${c}`);
  for (const v of needsHuman) {
    console.log(`   NEEDS A HUMAN:       a hook reads ${v}, a variable the hook contract does not define`);
    console.log('                        its checks never fire, so the protection it looks like is imaginary');
  }
  if (dryRun) { console.log(`   (dry run, nothing written): ${path}`); return { changed: changes.length > 0 }; }
  if (changes.length) {
    const bak = `${path}.bak.${new Date().toISOString().replace(/[:.]/g, '-')}`;
    copyFileSync(path, bak);
    console.log(`   backup:              ${bak}`);
    writeFileSync(path, JSON.stringify(settings, null, 2) + '\n', 'utf8');
    console.log(`   wrote:               ${path}`);
  }
  return { changed: changes.length > 0 };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const dryRun = process.argv.includes('--dry-run');
  const projectIdx = process.argv.indexOf('--project');
  const project = projectIdx > -1 ? process.argv[projectIdx + 1] : null;
  const withUser = process.argv.includes('--user');

  if (project || withUser) {
    // The framework owns a project's .claude/settings.json; settings.local.json and the user-level
    // file are personal, so those are treated surgically.
    const levels = project ? settingsLevels(project) : settingsLevels(process.cwd());
    const targets = [];
    if (project) {
      targets.push({ path: levels.find(l => l.name === 'project').path, owned: true });
      targets.push({ path: levels.find(l => l.name === 'local').path, owned: false });
    }
    if (withUser) targets.push({ path: levels.find(l => l.name === 'user').path, owned: false });

    console.log(`Curing settings${dryRun ? ' (dry run)' : ''}:`);
    let touched = 0;
    for (const t of targets) {
      console.log(` ${t.path}`);
      if (cureFile(t.path, { owned: t.owned, dryRun }).changed) touched++;
    }
    console.log(touched
      ? `${touched} file(s) changed. Settings are read when a session starts — restart Claude Code for them to take effect.`
      : 'nothing to change.');
    process.exit(0);
  }

  const template = buildTemplateSettings();

  if (check) {
    let failed = false;
    const onDisk = readJson(TEMPLATE_PATH);
    if (onDisk && onDisk.__parseError) {
      console.error(`FAIL ${TEMPLATE_PATH}: the file does not parse as JSON — ${onDisk.__parseError}`);
      failed = true;
    } else if (JSON.stringify(onDisk, null, 2) !== JSON.stringify(template, null, 2)) {
      console.error(`FAIL ${TEMPLATE_PATH} drifted from the policy. Rebuild with: node tools/gen-settings.mjs`);
      failed = true;
    }
    const self = readJson(SELF_PATH);
    if (self && self.__parseError) {
      console.error(`FAIL ${SELF_PATH}: the file does not parse as JSON — ${self.__parseError}`);
      failed = true;
    } else {
      const problems = diffAgainstPolicy(self || {});
      if (problems.length) {
        console.error(`FAIL ${SELF_PATH} drifted from the policy:`);
        for (const p of problems) console.error(`   - ${p}`);
        failed = true;
      }
    }
    if (failed) process.exit(1);
    console.log('OK settings match the core/permissions-policy.mjs policy');
    process.exit(0);
  }

  writeFileSync(TEMPLATE_PATH, JSON.stringify(template, null, 2) + '\n', 'utf8');
  console.log(`wrote ${TEMPLATE_PATH}`);
  const self = readJson(SELF_PATH);
  const updated = applyPolicyToSettings(self && !self.__parseError ? self : {});
  writeFileSync(SELF_PATH, JSON.stringify(updated, null, 2) + '\n', 'utf8');
  console.log(`updated ${SELF_PATH}`);
}
